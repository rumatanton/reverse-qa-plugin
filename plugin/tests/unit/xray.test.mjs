// Xray formats: canonical cases → bulk JSON / .feature / importer CSV, and Playwright report → Xray JSON results.
// official-bulk-example.json is copied verbatim from Xray's Postman collection (Xray-App/xray-postman-collections,
// BSD-3-Clause), so the validator is checked against Xray's own example, not against our reading of the docs.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import YAML from 'yaml';
import { validateCases, validateBulkTests, toBulk, toFeatures, toImporterCsv, toXrayResults, statusOf, caseIdsOf, previewId, labelsOf } from '../../lib/xray.mjs';
import { parseCsv } from '../../lib/csv.mjs';
import { PLUGIN } from '../helpers.mjs';

const FX = path.join(PLUGIN, 'tests', 'fixtures', 'xray');
const OFFICIAL = JSON.parse(fs.readFileSync(path.join(FX, 'official-bulk-example.json'), 'utf8'));
const CASES = YAML.parse(fs.readFileSync(path.join(FX, 'mini-shop-cases.yaml'), 'utf8'));
const REQS = new Set(YAML.parse(fs.readFileSync(path.join(FX, 'mini-shop-requirements.yaml'), 'utf8')).map((r) => r.id));
const KEYS = { 'REQ-AUTH-001': 'QA-11', 'REQ-PAY-001': 'QA-12' };

test("the validator accepts Xray's own official bulk-import example", () => {
  assert.deepEqual(validateBulkTests(OFFICIAL), []);
});

test('validateBulkTests names each format break', () => {
  const bad = structuredClone(OFFICIAL);
  bad[0].testtype = 'Automated';
  bad[1].steps[0].action = '';
  bad[1].update.issuelinks[0].add.type.name = 'Relates';
  bad[1].update.issuelinks[0].add.outwardIssue.key = 'not a key';
  bad[2].fields.project.key = 'qa';
  bad[2].fields.labels = ['two words'];
  const p = validateBulkTests(bad);
  for (const want of ['testtype must be', 'step 1 needs an action', '"Test" link type', 'is not a Jira key', 'project.key', 'contains whitespace']) assert.ok(p.some((x) => x.includes(want)), want);
  assert.deepEqual(validateBulkTests({}), ['payload must be a JSON array of tests']);
  assert.ok(validateBulkTests(Array(1001).fill(OFFICIAL[1]))[0].includes('at most 1000'));
});

test('validateCases accepts the fixture and catches schema and traceability problems', () => {
  assert.deepEqual(validateCases(CASES, REQS), { problems: [], uncovered: [] });
  const bad = structuredClone(CASES);
  bad.cases[0].id = 'AUTH-1';
  bad.cases[1].gherkin = 'Scenario: x\nGiven a';
  bad.cases[2].requirement = 'REQ-NOPE-001';
  bad.cases[3].priority = 'High';
  bad.cases.push({ ...bad.cases[3], steps: [{ action: 'x' }] });
  const { problems, uncovered } = validateCases(bad, REQS);
  for (const want of ['id must look like', 'no Feature/Scenario line', 'REQ-NOPE-001 is not in requirements.yaml', 'priority must be', 'duplicate id', 'has no expected result']) assert.ok(problems.some((x) => x.includes(want)), want);
  assert.deepEqual(uncovered, ['REQ-PAY-001']);
});

test('toBulk renders Xray-native tests that pass the validator, with links only for mapped requirements', () => {
  const bulk = toBulk(CASES, { projectKey: 'QA', jiraKeys: KEYS, repositoryPath: 'reverse-qa/mini-shop' });
  assert.deepEqual(validateBulkTests(bulk), []);
  assert.equal(bulk.length, 4);
  assert.deepEqual(bulk[0].steps[1], { action: 'Submit the form', data: 'email=ann@example.test, password=secret', result: 'The browser is redirected to index.php and a session cookie is set' });
  assert.equal(bulk[1].testtype, 'Cucumber');
  assert.match(bulk[1].gherkin_def, /^Given the database is reset to the seed\nWhen I log in as/);
  assert.deepEqual(bulk[0].update.issuelinks, [{ add: { type: { name: 'Test' }, outwardIssue: { key: 'QA-11' } } }]);
  assert.equal(bulk[3].update, undefined, 'REQ-ADM-001 has no Jira key: no link, but the label keeps traceability');
  assert.ok(bulk[3].fields.labels.includes('REQ-ADM-001'));
  assert.equal(bulk[3].xray_test_repository_folder, 'reverse-qa/mini-shop/authz');
  assert.match(bulk[0].fields.description, /\*Automated by:\* framework\/tests\/t3-roles\/authn\/login\.spec\.ts/);
  assert.deepEqual(labelsOf({ id: 'TC-A-001', requirement: ['R 1'], priority: 'P1', tier: 'api', technique: 'use-case', tags: ['ASVS 1'] }), ['reverse-qa', 'TC-A-001', 'R_1', 'P1', 'tier-api', 'use-case', 'ASVS_1']);
});

test('toFeatures writes one feature per area with traceability tags; an Examples table makes a Scenario Outline', () => {
  const files = toFeatures(CASES, { jiraKeys: KEYS });
  assert.deepEqual(Object.keys(files), ['adm.feature', 'auth.feature', 'pay.feature']);
  assert.equal(
    files['auth.feature'].split('\n').slice(0, 9).join('\n'),
    [
      'Feature: auth',
      '  Test cases generated by reverse-qa from approved requirements.',
      '',
      '  @TC-AUTH-001 @REQ_QA-11 @P1 @authn',
      '  Scenario: Customer logs in with a registered email and the right password',
      '    Given The database is reset to the seed',
      '    When Open login.php',
      '    Then The login form shows email and password fields',
      '    And Submit the form with "email=ann@example.test, password=secret"',
    ].join('\n'),
  );
  assert.match(files['auth.feature'], /@TC-AUTH-002 @REQ_QA-11 @P1 @authn\n {2}Scenario Outline: Login is refused/);
  assert.match(files['auth.feature'], /\n {6}\| ann@example\.test \| wrong {4}\|/);
  assert.match(files['adm.feature'], /@REQ_REQ-ADM-001/, 'unmapped requirement keeps its REQ id');
});

test('toImporterCsv writes one row per step and shares the TCID across a case', () => {
  const rows = parseCsv(toImporterCsv(CASES, { jiraKeys: KEYS, repositoryPath: 'rq' }));
  assert.equal(rows.length, 2 + 1 + 2 + 1);
  assert.deepEqual([rows[0].TCID, rows[0].Summary, rows[0].Requirement, rows[0]['Repository Path']], ['TC-AUTH-001', 'Customer logs in with a registered email and the right password', 'QA-11', 'rq/authn']);
  assert.deepEqual([rows[1].TCID, rows[1].Summary, rows[1].Action], ['TC-AUTH-001', '', 'Submit the form']);
  assert.equal(rows[2]['Test Type'], 'Cucumber');
  assert.match(rows[2].Gherkin, /Examples:/);
});

const report = {
  suites: [
    {
      title: 'login.spec.ts',
      file: 'tests/t3-roles/authn/login.spec.ts',
      specs: [
        { title: 'customer logs in @TC-AUTH-001', tags: [], tests: [{ projectName: 'chromium', expectedStatus: 'passed', status: 'expected', results: [{ status: 'passed', duration: 1200, startTime: '2026-11-09T10:00:00.000Z' }] }] },
        { title: 'wrong password', tags: ['@TC-AUTH-002'], tests: [{ projectName: 'chromium', expectedStatus: 'passed', status: 'unexpected', results: [{ status: 'failed', duration: 500, startTime: '2026-11-09T10:00:02.000Z', error: { message: 'Expected "Invalid login"\nmore' } }] }] },
      ],
      suites: [
        {
          title: 'nested',
          specs: [
            { title: 'report leaks in 302 body @TC-ADM-001', tags: [], tests: [{ projectName: 'chromium', expectedStatus: 'failed', status: 'expected', results: [{ status: 'failed', duration: 300, startTime: '2026-11-09T10:00:03.000Z' }] }] },
            { title: 'flaky checkout @TC-PAY-001', tags: [], tests: [{ projectName: 'firefox', expectedStatus: 'passed', status: 'flaky', results: [{ status: 'failed' }, { status: 'passed', duration: 900, startTime: '2026-11-09T10:00:05.000Z' }] }] },
            { title: 'no case tag', tags: [], tests: [{ status: 'expected', results: [] }] },
            { title: 'not published @TC-NEW-001', tags: [], tests: [{ status: 'skipped', results: [] }] },
          ],
        },
      ],
    },
  ],
};

test('toXrayResults maps Playwright outcomes to Xray statuses per case', () => {
  const r = toXrayResults(report, { testKeys: { 'TC-AUTH-001': 'QA-101', 'TC-AUTH-002': 'QA-102', 'TC-ADM-001': 'QA-104', 'TC-PAY-001': 'QA-103' } });
  const by = Object.fromEntries(r.results.tests.map((t) => [t.testKey, t]));
  assert.equal(by['QA-101'].status, 'PASSED');
  assert.equal(by['QA-102'].status, 'FAILED');
  assert.match(by['QA-102'].comment, /Expected "Invalid login"$/m);
  assert.equal(by['QA-104'].status, 'FAILED');
  assert.match(by['QA-104'].comment, /known defect \(test\.fail\(\)\)/);
  assert.equal(by['QA-103'].status, 'PASSED');
  assert.match(by['QA-103'].comment, /flaky/);
  assert.deepEqual(r.unmapped, ['TC-NEW-001']);
  assert.deepEqual(r.unlinked, ['tests/t3-roles/authn/login.spec.ts: no case tag']);
  assert.equal(r.results.info.startDate, '2026-11-09T10:00:00.000Z');
  assert.equal(by['QA-101'].finish, '2026-11-09T10:00:01.200Z');
});

test('statusOf, caseIdsOf and previewId', () => {
  assert.deepEqual(statusOf({ status: 'skipped' }), { status: 'TODO', note: 'skipped' });
  assert.deepEqual(statusOf({ status: 'unexpected' }, { failed: 'FAIL' }), { status: 'FAIL', note: null });
  assert.deepEqual(caseIdsOf({ title: 'x @TC-A-001 and @TC-A-001', tags: ['@TC-B-002'] }), ['TC-A-001', 'TC-B-002']);
  assert.equal(previewId([1, 2]), previewId([1, 2]));
  assert.notEqual(previewId([1, 2]), previewId([2, 1]));
});
